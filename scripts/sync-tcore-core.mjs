// sync-tcore-core.mjs — copies the I-Core bot's decision engine into the app, unchanged, as js/tcore-core.js.
//   node scripts/sync-tcore-core.mjs [path/to/icore-core.js]        (default: bb-trail/icore-core.js)
//   node scripts/sync-tcore-core.mjs --check                          (exit 1 if the app copy is not the bot's file)
// The bot's text is wrapped in a closure only, so its top-level names (DEFAULTS, stats, backtest …) do not leak into the page;
// inside, it registers itself as globalThis.TCore exactly as it does in a browser. The I-Core setups indicator (js/icx.js) draws
// what TCore.backtest() returns, so the chart shows the bot's own trades, not a re-implementation.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url)), app = join(here, '..');
const args = process.argv.slice(2), check = args.includes('--check');
const src = args.find((a) => !a.startsWith('--')) || join(app, 'bb-trail', 'icore-core.js');
const out = join(app, 'js', 'tcore-core.js');
const HEAD = '// GENERATED by scripts/sync-tcore-core.mjs from the T-CORE bot (bb-trail) (icore-core.js). Do not edit: change the bot, then re-run the script.\n';
const sha = (s) => createHash('sha256').update(s).digest('hex');

// the bot's text, exactly as it is in the generated file (between the wrapper lines)
export function inner(generated) {
  const a = generated.indexOf('\n(function () {\n'), b = generated.lastIndexOf('\n})();\n');
  return a < 0 || b < 0 ? null : generated.slice(a + '\n(function () {\n'.length, b + 1);
}
function wrap(text, hash) {
  return `${HEAD}// source sha256 ${hash}\n(function () {\n${text}${text.endsWith('\n') ? '' : '\n'}})();\n`;
}

if (!existsSync(src)) { console.error('not found: ' + src); process.exit(1); }
// the bot registers itself as globalThis.ICore (it reuses I-Core's machinery); the page keeps I-Core and T-CORE apart, so rename it here
const text = readFileSync(src, 'utf8').replace(/\r\n/g, '\n').replace('globalThis.ICore = API', 'globalThis.TCore = API');
const want = wrap(text, sha(text));
if (check) {
  const have = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== want) { console.error('js/tcore-core.js is NOT the bot\'s current icore-core.js — run: node scripts/sync-tcore-core.mjs'); process.exit(1); }
  console.log('js/tcore-core.js matches the bot (sha256 ' + sha(text).slice(0, 12) + ')');
} else {
  writeFileSync(out, want);
  console.log('wrote js/tcore-core.js from ' + src + ' (sha256 ' + sha(text).slice(0, 12) + ')');
}
