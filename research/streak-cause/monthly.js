// monthly.js — month-by-month TRI-CORE result from results.json (run analyze.js first). Writes MONTHLY.md.
'use strict';
const fs = require('fs'), path = require('path');
const J = JSON.parse(fs.readFileSync(path.join(__dirname, 'results.json'), 'utf8'));
const M = [...J.months].sort((a, b) => a.k.localeCompare(b.k));
const f = (v) => (v >= 0 ? '+' : '') + v.toFixed(1), md = [], P = (s = '') => md.push(s);
P('# TRI-CORE month by month (Jan 2020 to Oct 2026)');
P('Live rules v3, live coins, Binance 4h, costs + funding in R, booked at trade exit. TRI-CORE = 0.5 BB-CORE + 0.25 I-CORE + 0.25 T-CORE. Generated by `node monthly.js`.'); P();
const neg = (k) => M.filter((m) => (k < 0 ? m.R : m.by[k]) < 0).length;
const streak = (k) => { let b = 0, c = 0; for (const m of M) { c = (k < 0 ? m.R : m.by[k]) < 0 ? c + 1 : 0; b = Math.max(b, c); } return b; };
let e = 0, pk = 0, dd = 0; for (const m of M) { e += m.R; pk = Math.max(pk, e); dd = Math.max(dd, pk - e); }
const s = M.map((m) => m.R).sort((a, b) => a - b);
P('## Summary'); P('| | TRI-CORE | BB-CORE | I-CORE | T-CORE |'); P('|---|---|---|---|---|');
P(`| Months | ${M.length} | ${M.length} | ${M.length} | ${M.length} |`);
P(`| Negative months | **${neg(-1)} (${(100 * neg(-1) / M.length).toFixed(0)}%)** | ${neg(0)} | ${neg(1)} | ${neg(2)} |`);
P(`| Longest run of negative months | **${streak(-1)}** | ${streak(0)} | ${streak(1)} | ${streak(2)} |`);
P(`| Average month | ${f(e / M.length)} | ${[0, 1, 2].map((b) => f(M.reduce((a, m) => a + m.by[b], 0) / M.length)).join(' | ')} |`);
P(`| Median month | ${f(s[s.length >> 1])} | | | |`);
P(`| Best / worst month | ${f(s[s.length - 1])} / ${f(s[0])} | | | |`);
P(`| Max drawdown (month ends) | ${f(-dd)} | | | |`); P();
P('## Each year'); P('| Year | TRI-CORE R | Positive months | Negative months | Worst month |'); P('|---|---|---|---|---|');
for (const y of [...new Set(M.map((m) => m.k.slice(0, 4)))]) { const Y = M.filter((m) => m.k.startsWith(y)), w = Y.reduce((a, m) => (m.R < a.R ? m : a)); P(`| ${y} | ${f(Y.reduce((a, m) => a + m.R, 0))} | ${Y.filter((m) => m.R >= 0).length} | ${Y.filter((m) => m.R < 0).length} | ${w.k} ${f(w.R)} |`); }
P(); P('## Every month'); P('| Month | TRI-CORE R | BB-CORE R | I-CORE R | T-CORE R | Running total | Market efficiency |'); P('|---|---|---|---|---|---|---|');
e = 0; for (const m of M) { e += m.R; P(`| ${m.k} | ${m.R < 0 ? '**' + f(m.R) + '**' : f(m.R)} | ${m.by.map(f).join(' | ')} | ${f(e)} | ${m.er.toFixed(2)} |`); }
fs.writeFileSync(path.join(__dirname, 'MONTHLY.md'), md.join('\n')); console.log(md.join('\n'));
