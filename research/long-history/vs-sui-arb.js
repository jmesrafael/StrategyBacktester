// vs-sui-arb.js — the six long-history candidates (ENJ, ONE, GRT, KSM, UNI, ANKR) against SUI and ARB on the SAME window and the SAME data
// (candle library: Binance USDT-M perp 4h + real funding), same engine and bot rules as bystrat.js / sui-arb.js.
//   node vs-sui-arb.js  -> VS-SUI-ARB.md, vs-sui-arb.json
// Window: Jun 10, 2023 (SUI warm-up done) -> Nov 11, 2026. Also: each coin added to each bot's current coins (what it does to the bot).
'use strict';
const fs = require('fs'), path = require('path');
const H = path.join(__dirname, '../strat-hunt-nov6'), C = require('../../candles/candles.js');
const { run, COST } = require(path.join(H, 'engine.js')), { S, makeCtx, exitOf } = require(path.join(H, 'strategies.js'));
const BOTS = { 'BB-CORE': 'BBX', 'I-CORE': 'P7', 'T-CORE': 'P14' }, WT = { 'BB-CORE': .5, 'I-CORE': .25, 'T-CORE': .25 };
const BASE = { 'BB-CORE': ['SOL', 'NEAR', 'ADA', 'GALA'], 'I-CORE': ['SOL', 'NEAR', 'ADA', 'GALA'], 'T-CORE': ['SOL', 'NEAR', 'ADA', 'GALA', 'ETH'] };
const CAND = ['SUI', 'ARB', 'ENJ', 'ONE', 'GRT', 'KSM', 'UNI', 'ANKR'];
const MEXC = { SUI: 37.0, ARB: 15.1, ENJ: 0.2, ONE: 4.5, GRT: 0.2, KSM: 0.1, UNI: 42.7, ANKR: 0.1 };   // 24h USDT volume on MEXC futures, $M, Nov 12, 2026 (all 8 have a live USDT contract; ANKR was first misread as missing)
const W0 = Date.UTC(2023, 5, 10) / 1000, END = Date.UTC(2026, 10, 12) / 1000, Y26 = Date.UTC(2026, 0, 1) / 1000;
const by = (id) => S.find((s) => s.id === id), T = {};
for (const c of [...new Set([...CAND, ...BASE['T-CORE']])]) {
  const B = C.load(c, '4h').map((r) => ({ time: r[0], open: r[1], high: r[2], low: r[3], close: r[4], volume: r[5] })), F = C.funding(c);
  const x = makeCtx(B, '4h'), bbc = by('bb-core').build(x), built = { BBX: bbc, P7: by('i-core').build(x), P14: { ...bbc, stopL: null, stopS: null } };
  T[c] = {};
  for (const [bot, p] of Object.entries(BOTS)) T[c][bot] = run(B, x.atr14, built[p], exitOf(p, x), F, 14400, COST).trades.filter((t) => t.tExit > W0 && t.tExit <= END).map((t) => ({ x: t.tExit, R: t.R }));
  T[c].TRI = Object.keys(BOTS).flatMap((b) => T[c][b].map((t) => ({ x: t.x, R: t.R * WT[b] })));
}
const MN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const mk = (x) => { const d = new Date(x * 1e3); return d.getUTCFullYear() * 12 + d.getUTCMonth(); };
const K0 = mk(W0), K1 = mk(END - 1), NM = K1 - K0 + 1;   // 42 months
const months = (tr) => { const m = Array(NM).fill(0); for (const t of tr) m[mk(t.x) - K0] += t.R; return m; };
function st(tr) {
  const s = [...tr].sort((a, b) => a.x - b.x); let e = 0, pk = 0, dd = 0; for (const t of s) { e += t.R; pk = Math.max(pk, e); dd = Math.max(dd, pk - e); }
  const w = s.filter((t) => t.R > 0), gw = w.reduce((a, t) => a + t.R, 0), gl = -s.filter((t) => t.R <= 0).reduce((a, t) => a + t.R, 0);
  const m = months(s), yr = (y) => s.filter((t) => new Date(t.x * 1e3).getUTCFullYear() === y).reduce((a, t) => a + t.R, 0);
  const best = Math.max(...m);
  return { n: s.length, R: e, dd, rdd: dd ? e / dd : 0, pf: gl ? gw / gl : 0, win: s.length ? w.length / s.length : 0, pos: m.filter((v) => v > 1e-9).length, y23: yr(2023), y24: yr(2024), y25: yr(2025), y26: yr(2026), best, bestShare: e > 0 ? best / e : null, m };
}
const f = (v, d = 1) => (v >= 0 ? '+' : '−') + Math.abs(v).toFixed(d), out = [], P = (s) => out.push(s);
const J = { coin: {}, add: {} };
for (const c of CAND) { J.coin[c] = {}; for (const b of [...Object.keys(BOTS), 'TRI']) J.coin[c][b] = st(T[c][b]); }
for (const b of Object.keys(BOTS)) { const base = st(BASE[b].flatMap((c) => T[c][b])); J.add[b] = { base }; for (const c of CAND) J.add[b][c] = st([...BASE[b], c].flatMap((k) => T[k][b])); }

P('# SUI and ARB against ENJ, ONE, GRT, KSM, UNI and ANKR (same window, same data)');
P('\nAll eight coins: Binance USDT-M perp 4h candles + real funding from the local candle library, the live bot rules, real fees and slippage, 1R per trade.');
P('Window Jun 10, 2023 → Nov 11, 2026 (42 months, the only period SUI and ARB have). Nov 2026 is partial. Generated by vs-sui-arb.js.');
P('\n## 0. Can the bots even trade it? (MEXC futures, 24h volume, Nov 12, 2026)');
P('| Coin | ' + CAND.join(' | ') + ' |\n|---|' + CAND.map(() => '---:').join('|') + '|');
P('| MEXC 24h volume | ' + CAND.map((c) => MEXC[c] == null ? '**no contract**' : `$${MEXC[c]}M`).join(' | ') + ' |');
for (const b of [...Object.keys(BOTS), 'TRI']) {
  P(`\n## ${b === 'TRI' ? 'TRI mix (BB 50 / I 25 / T 25)' : b}: each coin alone`);
  P('| Coin | 2023 (Jun–) | 2024 | 2025 | 2026 (to Nov 11) | Total R | Max DD | Return ÷ DD | Win rate | PF | + months | Best month share |');
  P('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
  for (const c of [...CAND].sort((a, b2) => J.coin[b2][b].rdd - J.coin[a][b].rdd)) { const s = J.coin[c][b]; P(`| ${['SUI', 'ARB'].includes(c) ? `**${c}**` : c} | ${f(s.y23)} | ${f(s.y24)} | ${f(s.y25)} | ${f(s.y26)} | **${f(s.R)}** | ${s.dd.toFixed(1)} | ${s.rdd.toFixed(2)} | ${(s.win * 100).toFixed(0)}% | ${s.pf.toFixed(2)} | ${s.pos}/42 | ${s.bestShare == null ? '–' : (s.bestShare * 100).toFixed(0) + '%'} |`); }
}
for (const b of Object.keys(BOTS)) {
  const base = J.add[b].base;
  P(`\n## ${b}: current coins + one coin (what it does to the bot)`);
  P(`Current coins (${BASE[b].join(', ')}): ${f(base.R)}R, max DD ${base.dd.toFixed(1)}R, return ÷ DD ${base.rdd.toFixed(2)}, ${base.pos}/42 positive months.`);
  P('| + coin | Total R | Δ R | Max DD | Δ DD | Return ÷ DD | Δ | + months | 2026 R |');
  P('|---|---:|---:|---:|---:|---:|---:|---:|---:|');
  for (const c of [...CAND].sort((a, b2) => J.add[b][b2].rdd - J.add[b][a].rdd)) { const s = J.add[b][c]; P(`| ${['SUI', 'ARB'].includes(c) ? `**${c}**` : c} | ${f(s.R)} | ${f(s.R - base.R)} | ${s.dd.toFixed(1)} | ${f(s.dd - base.dd)} | ${s.rdd.toFixed(2)} | ${f(s.rdd - base.rdd, 2)} | ${s.pos}/42 | ${f(s.y26)} |`); }
}
P('\n## 2026 month by month, each coin alone (R)');
const i26 = mk(Y26) - K0;
for (const b of [...Object.keys(BOTS), 'TRI']) {
  P(`\n### ${b === 'TRI' ? 'TRI mix' : b}`);
  P(`| Coin | ${MN.slice(0, 11).join(' | ')} | **2026** | + months |\n|---|${MN.slice(0, 11).map(() => '---:').join('|')}|---:|---:|`);
  const tot = Array(11).fill(0);
  for (const c of CAND) { const m = J.coin[c][b].m.slice(i26, i26 + 11); m.forEach((v, i) => (tot[i] += v)); P(`| ${['SUI', 'ARB'].includes(c) ? `**${c}**` : c} | ${m.map((v) => Math.abs(v) < 0.05 ? '0' : f(v)).join(' | ')} | **${f(m.reduce((a, v) => a + v, 0))}** | ${m.filter((v) => v > 1e-9).length}/11 |`); }
}
fs.writeFileSync(path.join(__dirname, 'VS-SUI-ARB.md'), out.join('\n') + '\n');
fs.writeFileSync(path.join(__dirname, 'vs-sui-arb.json'), JSON.stringify(J, (k, v) => (k === 'm' ? undefined : v)));
console.log(out.join('\n'));

// ---- combinations: the live plan re-checked on this data, and alternatives (account = BB 50 / I 25 / T 25)
const NONE = { 'BB-CORE': [], 'I-CORE': [], 'T-CORE': [] };
const acct = (add) => Object.keys(BOTS).flatMap((b) => [...BASE[b], ...add[b]].flatMap((c) => T[c][b].map((t) => ({ x: t.x, R: t.R * WT[b] }))));
const PLANS = [
  ['Current coins', NONE],
  ['Live plan: BB+ARB, T+SUI+ARB', { 'BB-CORE': ['ARB'], 'I-CORE': [], 'T-CORE': ['SUI', 'ARB'] }],
  ['BB+ARB, T+SUI (no ARB on T-CORE)', { 'BB-CORE': ['ARB'], 'I-CORE': [], 'T-CORE': ['SUI'] }],
  ['Live plan + UNI on I-CORE', { 'BB-CORE': ['ARB'], 'I-CORE': ['UNI'], 'T-CORE': ['SUI', 'ARB'] }],
  ['BB+ARB, I+UNI, T+SUI', { 'BB-CORE': ['ARB'], 'I-CORE': ['UNI'], 'T-CORE': ['SUI'] }],
  ['Paper only (not tradable on MEXC): BB+ENJ, I+ENJ, T+SUI', { 'BB-CORE': ['ENJ'], 'I-CORE': ['ENJ'], 'T-CORE': ['SUI'] }],
];
P('\n## Plans on the whole TRI-CORE account (Jun 2023 → Nov 2026)');
P('| Plan | Total R | Max DD | Return ÷ DD | + months | 2026 R |\n|---|---:|---:|---:|---:|---:|');
for (const [nm, add] of PLANS) { const s = st(acct(add)); P(`| ${nm} | ${f(s.R)} | ${s.dd.toFixed(1)} | ${s.rdd.toFixed(2)} | ${s.pos}/42 | ${f(s.y26)} |`); }
P('\n## T-CORE with the pair');
for (const extra of [[], ['SUI'], ['ARB'], ['SUI', 'ARB']]) { const s = st([...BASE['T-CORE'], ...extra].flatMap((c) => T[c]['T-CORE'])); P(`- T-CORE ${extra.length ? '+ ' + extra.join(' + ') : 'current'}: ${f(s.R)}R, max DD ${s.dd.toFixed(1)}R, return ÷ DD ${s.rdd.toFixed(2)}, ${s.pos}/42 positive months`); }
fs.writeFileSync(path.join(__dirname, 'VS-SUI-ARB.md'), out.join('\n') + '\n');
console.log(out.slice(out.findIndex((l) => l.startsWith('## Plans'))).join('\n'));
