// five-years.js — SUI, ARB, GRT, ONE, ENJ year by year on each bot and the TRI mix: R and the worst drop inside the year, plus all-years-positive.
// Candle library (Binance perp 4h + funding), live bot rules, 1R per trade.  node five-years.js -> FIVE-YEARS.md, five-years.json
'use strict';
const fs = require('fs'), path = require('path');
const H = path.join(__dirname, '../strat-hunt-nov6'), C = require('../../candles/candles.js');
const { run, COST } = require(path.join(H, 'engine.js')), { S, makeCtx, exitOf } = require(path.join(H, 'strategies.js'));
const BOTS = { 'BB-CORE': 'BBX', 'I-CORE': 'P7', 'T-CORE': 'P14' }, WT = { 'BB-CORE': .5, 'I-CORE': .25, 'T-CORE': .25 };
const COINS = ['SUI', 'ARB', 'GRT', 'ONE', 'ENJ'], YEARS = [2021, 2022, 2023, 2024, 2025, 2026], END = Date.UTC(2026, 10, 12) / 1000;
const by = (id) => S.find((s) => s.id === id), T = {};
for (const c of COINS) {
  const B = C.load(c, '4h').map((r) => ({ time: r[0], open: r[1], high: r[2], low: r[3], close: r[4], volume: r[5] })), F = C.funding(c);
  const x = makeCtx(B, '4h'), bbc = by('bb-core').build(x), built = { BBX: bbc, P7: by('i-core').build(x), P14: { ...bbc, stopL: null, stopS: null } };
  T[c] = {};
  for (const [bot, p] of Object.entries(BOTS)) T[c][bot] = run(B, x.atr14, built[p], exitOf(p, x), F, 14400, COST).trades.filter((t) => t.tExit <= END && new Date(t.tExit * 1e3).getUTCFullYear() >= 2021).map((t) => ({ x: t.tExit, R: t.R }));
  T[c].TRI = Object.keys(BOTS).flatMap((b) => T[c][b].map((t) => ({ x: t.x, R: t.R * WT[b] })));
}
const yr = (t) => new Date(t.x * 1e3).getUTCFullYear();
function st(tr) { const s = [...tr].sort((a, b) => a.x - b.x); let e = 0, pk = 0, dd = 0; for (const t of s) { e += t.R; pk = Math.max(pk, e); dd = Math.max(dd, pk - e); } return { R: e, dd, n: s.length }; }
const first = (c) => Math.min(...T[c]['BB-CORE'].map(yr)), f = (v) => (v >= 0 ? '+' : '−') + Math.abs(v).toFixed(0);
const out = [], P = (s) => out.push(s), J = {};
P('# SUI, ARB, GRT, ONE, ENJ: every year on every bot (R / worst drop inside the year)\n');
P('Binance perp 4h + real funding (candle library), live bot rules, real fees and slippage, 1R per trade. TRI mix = 50% BB-CORE + 25% I-CORE + 25% T-CORE. SUI and ARB start in 2023 (part year). 2026 runs to Nov 11. Generated by five-years.js.');
for (const b of ['BB-CORE', 'I-CORE', 'T-CORE', 'TRI']) {
  P(`\n## ${b === 'TRI' ? 'TRI mix' : b}`);
  P(`| Coin | ${YEARS.join(' | ')} | Total | Worst drop (all years) | Years positive |\n|---|${YEARS.map(() => '---').join('|')}|---:|---:|---|`);
  J[b] = {};
  for (const c of COINS) {
    const cells = YEARS.map((y) => { if (y < first(c)) return null; const s = st(T[c][b].filter((t) => yr(t) === y)); return s; });
    const live = cells.filter(Boolean), pos = live.filter((s) => s.R > 0).length, all = st(T[c][b]);
    J[b][c] = { years: Object.fromEntries(YEARS.map((y, i) => [y, cells[i]])), total: all.R, dd: all.dd, pos, n: live.length };
    P(`| ${c} | ${cells.map((s) => s ? `${f(s.R)} / ${s.dd.toFixed(0)}` : '–').join(' | ')} | **${f(all.R)}** | ${all.dd.toFixed(0)}R | ${pos}/${live.length}${pos === live.length ? ' ✅' : ''} |`);
  }
}
fs.writeFileSync(path.join(__dirname, 'FIVE-YEARS.md'), out.join('\n') + '\n');
fs.writeFileSync(path.join(__dirname, 'five-years.json'), JSON.stringify(J));
console.log(out.join('\n'));
